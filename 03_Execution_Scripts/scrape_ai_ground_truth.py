#!/usr/bin/env python3
"""
scrape_ai_ground_truth.py
─────────────────────────
Build an AI-audio GROUND-TRUTH dataset by searching YouTube with yt-dlp and
keeping ONLY tracks whose uploader explicitly declares the audio is AI-generated.

Positive-only validation
─────────────────────────
No negative filtering ("not AI").  Instead a strict regex WHITELIST (Python `re`)
scans each video's title + description + tags for an explicit AI declaration.
Key safety properties (see self-test at the bottom):
  • \b word boundaries so `@suno`, `#suno`, `suno.com`, `SunoAI` all match…
  • …but `studio` / `audio` NEVER trigger the `udio` rule (no substring hits).
If no definitive positive match is found, the video is skipped.

Metadata-only staging (downloads DISABLED)
───────────────────────────────────────────
  1. `extract_flat=True` search — cheap enumeration of candidate results.
  2. per-video `extract_info(download=False)` — flat mode does NOT expose the
     description / tags / duration we need, so we pull full metadata (still no
     audio download) for the two gates below.
  3. GATE 1 — regex AI whitelist on title + description + tags.
     GATE 2 — duration window (MIN_DURATION..MAX_DURATION s) to drop tutorials
              and podcasts.
  4. Videos passing BOTH gates are STAGED (not downloaded) to a review file:
         verified_ai_links.txt   (project root)
     one line each:  [seconds]s | [Title] | [URL]
  The MP3-download pipeline is commented out (see download_mp3 below).

Usage:
    python3 scrape_ai_ground_truth.py                       # default 4 queries x 20
    python3 scrape_ai_ground_truth.py --per-query 30
    python3 scrape_ai_ground_truth.py --queries "Suno AI full song" "Udio track"
    python3 scrape_ai_ground_truth.py --selftest            # regex validation only
"""

import os, re, sys, argparse
import yt_dlp                                    # download disabled; used for search/metadata only

HERE       = os.path.dirname(os.path.abspath(__file__))
ROOT       = os.path.dirname(HERE)                             # project root
OUT_DIR    = os.path.join(HERE, "data", "ground_truth_ai")    # (unused: MP3 download disabled)
LINKS_FILE = os.path.join(ROOT, "verified_ai_links.txt")      # staged links for manual review

# Duration acceptance window (seconds).  Rejects tutorials / podcasts (too long)
# and stray clips (too short), keeping song-length audio only.  Inclusive bounds.
MIN_DURATION = 90
MAX_DURATION = 300

# Explicit, targeted search queries (top-N results enumerated per query).
DEFAULT_QUERIES = [
    "AI generated music",
    "Suno AI full song",
    "Udio track",
    "AI music official audio",
]

# ── Positive-only AI whitelist ─────────────────────────────────────────────────
# Each entry: (compiled pattern, human-readable keyword for logging).
# Notes on the tricky ones:
#   \budio(...)  -> the leading \b demands a word boundary immediately BEFORE 'u',
#                   which does NOT exist inside "st|udio" or "a|udio" (t/a are word
#                   chars), so `studio` and `audio` can never match.  A boundary
#                   DOES exist after '@', '#', '.', or whitespace, so "@udio",
#                   "#udio", "udio.com" all match.
#   suno|udio (?:[\s.\-_]*ai)?  -> also catches the very common glued forms
#                   "SunoAI" / "suno.ai" / "udio-ai" while still respecting \b.
_FLAGS = re.IGNORECASE
AI_PATTERNS = [
    (re.compile(r"\bsuno(?:[\s.\-_]*ai)?\b", _FLAGS),                         "suno"),
    (re.compile(r"\budio(?:[\s.\-_]*ai)?\b", _FLAGS),                         "udio"),
    (re.compile(r"\bai[\s.\-_]*generated\b", _FLAGS),                         "ai generated"),
    (re.compile(r"\bgenerated[\s.\-_]*(?:by|with|using)[\s.\-_]*ai\b", _FLAGS),"generated by ai"),
    (re.compile(r"\bai[\s.\-_]*music\b", _FLAGS),                             "ai music"),
    (re.compile(r"\bai[\s.\-_]*song\b", _FLAGS),                              "ai song"),
    (re.compile(r"\bai[\s.\-_]*(?:cover|vocals?|track)\b", _FLAGS),           "ai cover/vocals"),
    (re.compile(r"\bmade[\s.\-_]*with[\s.\-_]*(?:suno|udio|ai)\b", _FLAGS),   "made with ai"),
]


def find_ai_declaration(text: str):
    """Return the first matched keyword (str) or None if no explicit AI claim."""
    if not text:
        return None
    for pattern, keyword in AI_PATTERNS:
        if pattern.search(text):
            return keyword
    return None


# ── Step 1a: flat search (metadata only) ───────────────────────────────────────
def search_candidates(query: str, n: int):
    """Enumerate up to `n` search results as flat metadata (id/title/url)."""
    opts = {"quiet": True, "no_warnings": True, "extract_flat": True, "skip_download": True}
    with yt_dlp.YoutubeDL(opts) as ydl:
        info = ydl.extract_info(f"ytsearch{n}:{query}", download=False)
    return [e for e in (info.get("entries") or []) if e]


# ── Step 1b: full metadata (still NO download) for description + tags ──────────
def fetch_metadata(url: str) -> dict:
    """extract_flat omits description/tags, so pull full metadata (download=False)."""
    opts = {"quiet": True, "no_warnings": True, "skip_download": True, "noplaylist": True}
    with yt_dlp.YoutubeDL(opts) as ydl:
        info = ydl.extract_info(url, download=False)
    return {
        "title":       info.get("title") or "",
        "description": info.get("description") or "",
        "tags":        info.get("tags") or [],
        "uploader":    info.get("uploader") or "",
        "duration":    info.get("duration"),          # seconds (float/int) or None
        "webpage_url": info.get("webpage_url") or url,
    }


