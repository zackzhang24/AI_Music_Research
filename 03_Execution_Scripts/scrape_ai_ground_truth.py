def _load_existing_urls(path: str) -> set:
    """URLs already staged in a prior run, so re-runs don't append duplicates."""
    urls = set()
    if os.path.exists(path):
        with open(path, "r", encoding="utf-8") as f:
            for ln in f:
                parts = ln.rstrip("\n").split(" | ")
                if len(parts) >= 3:
                    urls.add(parts[-1].strip())
    return urls


# ── Main pipeline ──────────────────────────────────────────────────────────────
def main():
    ap = argparse.ArgumentParser(description="Stage explicitly-declared AI tracks from YouTube to a review file.")
    ap.add_argument("--queries", nargs="+", default=DEFAULT_QUERIES)
    ap.add_argument("--per-query", type=int, default=20, help="results to enumerate per query")
    args = ap.parse_args()

    print("=" * 72)
    print("AI ground-truth scraper — regex whitelist + duration filter -> staged links")
    print(f"  Queries        : {len(args.queries)}  x  {args.per_query} results each")
    print(f"  Duration window: {MIN_DURATION}-{MAX_DURATION}s (inclusive)")
    print(f"  Staging file   : {LINKS_FILE}")
    print(f"  Downloads      : DISABLED (staging links for manual review only)")
    print("=" * 72)

    seen_ids       = set()
    existing_urls  = _load_existing_urls(LINKS_FILE)
    staged = skip_regex = skip_dur = dup = 0

    # Append mode: verified links accumulate across runs (dupes are filtered).
    links_fh = open(LINKS_FILE, "a", encoding="utf-8")

    for q in args.queries:
        print(f"\n🔎 Searching: \"{q}\"")
        try:
            candidates = search_candidates(q, args.per_query)
        except Exception as exc:
            print(f"   [search error] {exc}", file=sys.stderr)
            continue
        print(f"   {len(candidates)} candidate(s) returned.")

        for entry in candidates:
            vid = entry.get("id")
            url = entry.get("url") or entry.get("webpage_url") or (f"https://www.youtube.com/watch?v={vid}" if vid else None)
            if not url or vid in seen_ids:
                continue
            seen_ids.add(vid)

            # ── Metadata-only probe (title + description + tags + duration) ────
            try:
                meta = fetch_metadata(url)
            except Exception as exc:
                print(f"   [meta error] {entry.get('title','?')[:50]}: {exc}", file=sys.stderr)
                continue

            title    = meta["title"][:70]
            duration = meta["duration"]
            web_url  = meta["webpage_url"]

            # ── Gate 1: positive-only AI whitelist ────────────────────────────
            haystack = " ".join([meta["title"], meta["description"], " ".join(meta["tags"])])
            keyword = find_ai_declaration(haystack)
            if keyword is None:
                skip_regex += 1
                print(f"   ⏭️  Skipped: No explicit AI declaration in text — \"{title}\"")
                continue

            # ── Gate 2: duration window (filters tutorials / podcasts) ─────────
            if duration is None or not (MIN_DURATION <= duration <= MAX_DURATION):
                skip_dur += 1
                shown = f"{int(duration)}s" if duration else "unknown length"
                print(f"   ⏭️  Skipped: Failed duration window ({shown})")
                continue

            # ── Passed BOTH gates -> stage link to text file (no download) ─────
            if web_url in existing_urls:
                dup += 1
                print(f"   ↩️  Already staged (duplicate) — \"{title}\"")
                continue

            line = f"{int(duration)}s | {meta['title']} | {web_url}"
            links_fh.write(line + "\n")
            links_fh.flush()
            existing_urls.add(web_url)
            staged += 1
            print(f"   ➕ Added to txt: \"{title}\"  [matched: '{keyword}', {int(duration)}s]")

    links_fh.close()

    print("\n" + "=" * 72)
    print(f"DONE — {staged} verified AI link(s) staged to {os.path.basename(LINKS_FILE)}.")
    print(f"  Skipped (no AI declaration) : {skip_regex}")
    print(f"  Skipped (duration window)   : {skip_dur}")
    print(f"  Skipped (already staged)    : {dup}")
    print(f"Review file: {LINKS_FILE}")
    print("=" * 72)


# ── Self-test: the adversarial regex cases the spec calls out ──────────────────
def _selftest():
    must_match = [
        "Made with Suno",           # suno
        "check @suno on twitter",   # @suno
        "#suno #aimusic",           # #suno
        "generated on suno.com",    # suno.com
        "SunoAI banger",            # glued SunoAI
        "created in Udio",          # udio
        "@udio release",            # @udio
        "udio.com track",           # udio.com
        "this is an AI generated song",   # ai generated
        "AI-generated instrumental",      # ai-generated
        "full ai music mix",              # ai music
        "generated by AI",                # generated by ai
        "made with ai",                   # made with ai
    ]
    must_not_match = [
        "recorded in my home studio",     # studio  -> must NOT hit \budio\b
        "high quality audio only",        # audio   -> must NOT hit \budio\b
        "professional studio audio mix",  # both traps in one string
        "a relaxing piano piece",         # nothing AI
        "live acoustic session",          # 'acoustic' contains no whole-word trap
        "brainstorm session music",       # 'ai' inside 'brain' must not trigger
    ]
    ok = True
    for t in must_match:
        kw = find_ai_declaration(t)
        flag = "PASS" if kw else "FAIL"
        if not kw: ok = False
        print(f"  [{flag}] MATCH expected     | {t!r:45s} -> {kw}")
    for t in must_not_match:
        kw = find_ai_declaration(t)
        flag = "PASS" if kw is None else "FAIL"
        if kw is not None: ok = False
        print(f"  [{flag}] NO-match expected  | {t!r:45s} -> {kw}")
    print("\nSELF-TEST:", "ALL PASSED ✅" if ok else "FAILURES ❌")
    return ok


if __name__ == "__main__":
    if "--selftest" in sys.argv:
        sys.exit(0 if _selftest() else 1)
    main()
